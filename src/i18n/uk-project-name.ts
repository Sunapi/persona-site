function preserveCase(source: string, translation: string): string {
  if (source === source.toLocaleUpperCase('ru')) {
    return translation.toLocaleUpperCase('uk');
  }
  if (source[0] === source[0]?.toLocaleUpperCase('ru')) {
    return translation[0]?.toLocaleUpperCase('uk') + translation.slice(1);
  }
  return translation;
}

function orthographicFallback(word: string): string {
  return word
    .replaceAll('ё', 'ьо')
    .replaceAll('ъ', '’')
    .replaceAll('ы', 'и')
    .replaceAll('э', 'е')
    .replace(/ый$/u, 'ий')
    .replace(/ая$/u, 'а')
    .replace(/яя$/u, 'я')
    .replace(/ое$/u, 'е')
    .replace(/ые$/u, 'і')
    .replace(/ых$/u, 'их');
}

export function ukProjectName(source: string): string {
  let translated = source;
  for (const [pattern, replacement] of phraseReplacements) {
    translated = translated.replace(pattern, replacement);
  }

  const result = translated.replace(/[\p{Script=Cyrillic}’]+/gu, (word) => {
    if (/[іїєґ]/iu.test(word)) return word;
    const lower = word.toLocaleLowerCase('ru');
    const replacement = wordReplacements[lower] ?? orthographicFallback(lower);
    return preserveCase(word, replacement);
  });

  return source[0] === source[0]?.toLocaleUpperCase('ru')
    ? result[0]?.toLocaleUpperCase('uk') + result.slice(1)
    : result;
}
